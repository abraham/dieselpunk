import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { defineBrowserCommand, playwright } from '@vitest/browser-playwright';
import { defineConfig } from 'vitest/config';
import {
  browserCommands,
  browserRun,
  preBundled,
  selectedEngines,
} from '@dieselpunk/testing/vitest';
import { parseSelection } from './test/browser/fixtures/groups.ts';

const run = browserRun(
  fileURLToPath(new URL('.', import.meta.url)),
  ['src/**/*.test.ts', 'test/browser/**/*.test.ts'],
  [
    'test/browser/a11y.test.ts',
    'test/browser/reflow.test.ts',
    'test/browser/overlays-a11y.test.ts',
  ],
  process.env,
  parseSelection,
);

// The manifest is generated by `npm run build:manifest`, which `pretest:browser` runs.
const readManifest = defineBrowserCommand<[]>(async () => {
  const file = fileURLToPath(new URL('./custom-elements.json', import.meta.url));
  return JSON.parse(await readFile(file, 'utf8')) as unknown;
});

export default defineConfig({
  // Tests always run with development warnings, and need no built dist/ to resolve #dev.
  resolve: {
    alias: [
      {
        find: /^#dev$/,
        replacement: fileURLToPath(new URL('./src/utilities/dev.dev.ts', import.meta.url)),
      },
    ],
  },
  optimizeDeps: { include: preBundled },
  test: {
    include: run.include,
    provide: run.provide,
    passWithNoTests: run.passWithNoTests,
    browser: {
      enabled: true,
      headless: true,
      provider: playwright(),
      instances: selectedEngines().map((browser) => ({ browser })),
      commands: { ...browserCommands, readManifest },
    },
  },
});
