import { baseTokens } from '../src/tokens/base.ts';
import type { TokenMap } from '../src/tokens/base.ts';
import { density, densityModes } from '../src/tokens/density.ts';
import { autoLightThemeName, defaultThemeName, themeNames, themes } from '../src/tokens/themes.ts';
import type { ThemeName } from '../src/tokens/themes.ts';

const HEADER = '/* Generated by scripts/build-css.ts from src/tokens. Do not edit. */\n';

function declarations(tokens: TokenMap, indent: string): string {
  return Object.entries(tokens)
    .map(([name, value]) => {
      if (/[;{}]/.test(value)) {
        throw new Error(`Token "${name}" has a value that would break CSS: ${value}`);
      }
      return `${indent}--punk-${name}: ${value};`;
    })
    .join('\n');
}

function themeBody(name: ThemeName, indent: string): string {
  const theme = themes[name];
  return `${indent}color-scheme: ${theme.colorScheme};\n${declarations(theme.tokens, indent)}`;
}

function rule(selector: string, body: string, indent = ''): string {
  return `${indent}${selector} {\n${body}\n${indent}}`;
}

/**
 * Base tokens, the default theme, and density rules.
 * `:where(:root)` has zero specificity so any theme or density attribute overrides it
 * regardless of stylesheet order.
 */
export function renderTokensCss(): string {
  const blocks = [
    rule(':where(:root)', declarations(baseTokens, '  ')),
    rule(
      `:where(:root),\n[data-punk-theme="${defaultThemeName}"]`,
      themeBody(defaultThemeName, '  '),
    ),
    ...densityModes.map((mode) =>
      rule(`[data-punk-density="${mode}"]`, declarations(density[mode], '  ')),
    ),
  ];
  return `${HEADER}\n${blocks.join('\n\n')}\n`;
}

/** Attribute rules for every non-default theme, and the `auto` mapping. */
export function renderThemesCss(): string {
  const blocks = themeNames
    .filter((name) => name !== defaultThemeName)
    .map((name) => rule(`[data-punk-theme="${name}"]`, themeBody(name, '  ')));

  blocks.push(rule('[data-punk-theme="auto"]', themeBody(defaultThemeName, '  ')));
  blocks.push(
    rule(
      '@media (prefers-color-scheme: light)',
      rule('[data-punk-theme="auto"]', themeBody(autoLightThemeName, '    '), '  '),
    ),
  );
  return `${HEADER}\n${blocks.join('\n\n')}\n`;
}
